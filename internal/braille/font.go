func (f *Font) Draw(c *Canvas, x, y int, text string, scale int) {
	if scale < 1 {
		scale = 1
	}
	cx := x
	for _, r := range text {
		g, ok := f.Glyphs[r]
		if !ok {
			g = f.Glyphs[' ']
		}
		for gy, row := range g {
			for gx, ch := range row {
				if ch != '1' {
					continue
				}
				for sy := 0; sy < scale; sy++ {
					for sx := 0; sx < scale; sx++ {
						c.SetDot(cx+gx*scale+sx, y+gy*scale+sy)
					}
				}
			}
		}
		cx += f.Width*scale + scale
	}
}

func (f *Font) TextWidth(text string, scale int) int {
	if len(text) == 0 {
		return 0
	}
	if scale < 1 {
		scale = 1
	}
	return len(text)*f.Width*scale + (len(text)-1)*scale
}

func (f *Font) FitScale(text string, dotWidth, dotHeight, margin int) int {
	if text == "" {
		return 1
	}
	for s := 16; s >= 1; s-- {
		if f.TextWidth(text, s) <= dotWidth-2*margin && f.Height*s <= dotHeight-2*margin {
			return s
		}
	}
	return 1
}
